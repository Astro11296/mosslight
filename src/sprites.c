void load_sprites(void) {
    /* Load all sprite tiles into VRAM */
    for (uint8_t i = 0; i < SPRITE_COUNT; i++) {
        set_sprite_data(i, 1, (unsigned char*)all_sprites[i]);
    }

    /* Set sprite size to 8x8 */
    SPRITES_8x8;
    SHOW_SPRITES;
}

/* Get the sprite tile for a wildlife ID */
uint8_t get_wildlife_sprite(uint8_t id) {
    if (id < WL_COUNT)
        return wildlife_sprite_map[id];
    return 0;
}

/* Player sprite tile offsets per direction */
static const uint8_t player_sprite_offsets[] = {
    0,  /* DIR_DOWN: tiles 0-3 */
    4,  /* DIR_UP: tiles 4-7 */
    8,  /* DIR_LEFT: tiles 8-11 */
    12, /* DIR_RIGHT: tiles 12-15 */
};

uint8_t get_player_sprite_base(uint8_t direction) {
    return player_sprite_offsets[direction & 3];
}
