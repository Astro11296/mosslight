void load_tiles(void) {
    /* Load all tiles into VRAM */
    uint8_t tid = 0;
    for (uint8_t i = 0; i < ALL_TILE_COUNT; i++) {
        set_bkg_data(tid, 1, (unsigned char*)all_tiles[i]);
        tid++;
    }

    /* Set BG palettes for CGB */
    set_bkg_palette(0, 1, bg_pal_0);
    set_bkg_palette(1, 1, bg_pal_1);
    set_bkg_palette(2, 1, bg_pal_2);
    set_bkg_palette(3, 1, bg_pal_3);

    /* Set OBJ palettes */
    set_sprite_palette(0, 1, obj_pal_0);
    set_sprite_palette(1, 1, obj_pal_1);
    set_sprite_palette(2, 1, obj_pal_2);
    set_sprite_palette(3, 1, obj_pal_3);

    SHOW_BKG;
    DISPLAY_ON;
}

uint8_t terrain_to_tile(uint8_t terrain) {
    switch (terrain) {
        case TERRAIN_GRASS:          return TILE_GRASS;
        case TERRAIN_SOIL:           return TILE_SOIL;
        case TERRAIN_FLOWER_BED:     return TILE_FLOWERBED;
        case TERRAIN_WOODLAND:       return TILE_WOODLAND;
        case TERRAIN_SHALLOW_WATER:  return TILE_SHALLOW;
        case TERRAIN_DEEP_WATER:     return TILE_DEEP;
        case TERRAIN_STONE:          return TILE_STONE;
        default:                     return TILE_GRASS;
    }
}
