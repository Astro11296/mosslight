#define FONT_CHAR_COUNT (sizeof(font_tiles)/16)

static bool font_loaded = false;

void load_font(void) {
    if (font_loaded) return;
    for (uint16_t i = 0; i < FONT_CHAR_COUNT; i++) {
        set_bkg_data(FONT_TILE_START + i, 1, (unsigned char*)font_tiles[i]);
    }
    font_loaded = true;
}

/* Convert char to font tile index */
static uint8_t char_to_tile(char c) {
    if (c >= 32 && c <= 95) {
        return FONT_TILE_START + (c - 32);
    }
    /* lowercase to uppercase */
    if (c >= 'a' && c <= 'z') {
        return FONT_TILE_START + (c - 'a' + 'A' - 32);
    }
    if (c == '\n') return 0; /* space */
    return FONT_TILE_START; /* space for unknown */
}

void draw_text(const char *s, uint8_t x, uint8_t y) {
    if (!font_loaded) load_font();
    uint8_t tx = x, ty = y;
    while (*s) {
        if (*s == '\n') {
            tx = x;
            ty++;
            s++;
            continue;
        }
        set_bkg_tile_xy(tx, ty, char_to_tile(*s));
        tx++;
        s++;
        if (tx >= SCREEN_TW) { tx = x; ty++; }
        if (ty >= SCREEN_TH) break;
    }
}

void draw_text_centered(const char *s, uint8_t y) {
    if (!font_loaded) load_font();
    uint8_t len = 0;
    const char *p = s;
    while (*p && *p != '\n') { len++; p++; }
    if (len > SCREEN_TW) len = SCREEN_TW;
    uint8_t x = (SCREEN_TW - len) / 2;
    draw_text(s, x, y);
}

/* Draw text using window layer instead of BG (for menus over gameplay) */
void draw_text_win(const char *s, uint8_t x, uint8_t y) {
    if (!font_loaded) load_font();
    uint8_t tx = x, ty = y;
    while (*s) {
        if (*s == '\n') { tx = x; ty++; s++; continue; }
        set_win_tile_xy(tx, ty, char_to_tile(*s));
        tx++; s++;
        if (tx >= SCREEN_TW) { tx = x; ty++; }
        if (ty >= SCREEN_TH) break;
    }
}
